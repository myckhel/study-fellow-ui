// Run after the final build. Fingerprints uncommitted build inputs and emitted bytes.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
const sha = bytes => createHash('sha256').update(bytes).digest('hex')
function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]).sort()
}
function record(path) { const bytes = readFileSync(path); return { path, bytes: bytes.length, sha256: sha(bytes) } }
const inputs = [...files('src'), ...files('public'), ...['package.json', 'bun.lock', 'bun.lockb', 'index.html', 'vite.config.ts', 'tsconfig.json', 'tsconfig.app.json', 'tsconfig.node.json'].filter(existsSync)].sort().map(record)
const artifacts = files('dist').map(record)
const appJS = artifacts.filter(file => file.path.startsWith('dist/assets/') && file.path.endsWith('.js'))
const totalJS = appJS.reduce((total, file) => total + file.bytes, 0)
const main = appJS.reduce((largest, file) => file.bytes > largest.bytes ? file : largest)
const result = {
  generatedAtUTC: new Date().toISOString(),
  status: 'technical candidate; external review and final freeze pending',
  frontendHEAD: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(),
  workingTree: execFileSync('git', ['status', '--short'], { encoding: 'utf8' }).trim(),
  note: 'HEAD is not a release commit. The input hash covers the enumerated source/public/config files, not the full build environment or content scanner inputs. The artifact hash identifies these generated bytes, including CSS and PWA output; compare it after any rebuild.',
  bunVersion: execFileSync('bun', ['--version'], { encoding: 'utf8' }).trim(),
  inputSHA256: sha(JSON.stringify(inputs)), artifactSHA256: sha(JSON.stringify(artifacts)),
  totalAppJSBytes: totalJS, mainJS: main,
  comparison: [797040, 738801].map(baselineBytes => ({ baselineBytes, changeBytes: totalJS - baselineBytes, changePercent: +((totalJS - baselineBytes) / baselineBytes * 100).toFixed(3) })),
  inputs, artifacts,
}
writeFileSync('plans/phase-4/build-manifest.json', JSON.stringify(result, null, 2) + '\n')
console.log(JSON.stringify({ totalAppJSBytes: totalJS, mainJS: main, comparison: result.comparison, inputSHA256: result.inputSHA256, artifactSHA256: result.artifactSHA256 }))
