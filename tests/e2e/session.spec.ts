for (const size of [{ width: 320, height: 500 }, { width: 375, height: 480 }, { width: 1280, height: 900 }]) {
  test(`layout and reduced motion ${size.width}x${size.height}`, async ({ page }, info) => {
    await page.setViewportSize(size)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await begin(page)
    const input = page.getByRole('textbox', { name: 'Message StudyFellow' })
    await input.fill('A longer message\n'.repeat(7))
    const canvas = page.getByRole('region', { name: 'Teaching and conversation' })
    const dock = page.locator('.session-dock')
    const region = await canvas.boundingBox()
    const controls = await dock.boundingBox()
    expect(region!.height).toBeGreaterThan(90)
    expect(region!.y + region!.height).toBeLessThanOrEqual(controls!.y + 1)
    expect(controls!.y + controls!.height).toBeLessThanOrEqual(size.height + 1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(size.width)
    if (size.width < 768) {
      await page.locator('.session-route-mobile > summary').click()
      await expect(page.locator('.session-route-mobile ol')).toBeVisible()
      await expect.poll(async () => (await canvas.boundingBox())!.height).toBeGreaterThanOrEqual(90)
      expect((await dock.boundingBox())!.y + (await dock.boundingBox())!.height).toBeLessThanOrEqual(size.height + 1)
      await input.fill('short')
      await expect.poll(async () => (await input.boundingBox())!.height).toBeLessThan(60)
      await page.locator('.session-route-mobile > summary').click()
    } else expect((await page.locator('.session-route-desktop').boundingBox())!.width).toBe(264)
    await page.screenshot({ path: info.outputPath(`phase1-${size.width}-teaching.png`) })
    await page.getByRole('button', { name: 'Continue', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Your turn' })).toBeFocused()
    await page.screenshot({ path: info.outputPath(`phase1-${size.width}-check.png`) })
    if (size.width < 768) {
      await input.fill('Light provides energy to help build sugar.')
      await page.getByRole('button', { name: 'Check answer' }).click()
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'Apply the idea' })).toBeFocused()
      await input.fill('Long transfer response\n'.repeat(7))
      await canvas.evaluate(node => { node.scrollTop = node.scrollHeight })
      await page.getByRole('button', { name: 'Send', exact: true }).click()
      await canvas.evaluate(node => { node.scrollTop = 0 })
      await expect.poll(() => canvas.evaluate(node => node.scrollTop)).toBe(0)
      await input.fill('A second response')
      await page.getByRole('button', { name: 'Send', exact: true }).click()
      await expect(page.getByRole('button', { name: 'New reply' })).toBeVisible()
      await input.fill('Long transfer response\n'.repeat(7))
      await page.locator('.session-route-mobile > summary').click()
      await expect.poll(async () => (await canvas.boundingBox())!.height).toBeGreaterThanOrEqual(90)
      expect((await dock.boundingBox())!.y + (await dock.boundingBox())!.height).toBeLessThanOrEqual(size.height + 1)
      await page.screenshot({ path: info.outputPath(`phase1-${size.width}-transfer-cue.png`) })
    }

  })
}

test('scroll follow respects earlier reading and exposes new reply cue', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 480 })
  await begin(page)
  const canvas = page.getByRole('region', { name: 'Teaching and conversation' })
  await canvas.evaluate(node => { node.scrollTop = node.scrollHeight })
  await page.getByRole('textbox', { name: 'Message StudyFellow' }).fill('First message')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await canvas.evaluate(node => { node.scrollTop = 0 })
  await expect.poll(() => canvas.evaluate(node => node.scrollTop)).toBe(0)
  await page.getByRole('textbox', { name: 'Message StudyFellow' }).fill('Second message')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('button', { name: 'New reply' })).toBeVisible()
  expect(await canvas.evaluate(node => node.scrollTop)).toBe(0)
  await page.getByRole('button', { name: 'New reply' }).click()
  await expect(page.getByText('Second message', { exact: true })).toBeVisible()
})

