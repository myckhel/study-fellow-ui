async function plan(page: Page, choice = 'Skip question') {
  await page.goto('/')
  await expect(page.locator('main')).not.toContainText(/\b(demo|legacy|precomputed|provenance)\b/i)
  await page.screenshot({ path: test.info().outputPath('plain-home.png'), fullPage: true })
  await page.getByRole('button', { name: 'Learn now' }).click()
  await page.getByRole('button', { name: 'Try photosynthesis' }).click()
  await page.getByRole('button', { name: choice, exact: true }).click()
}
async function begin(page: Page, choice = 'Skip question') {
  await plan(page, choice)
  await page.getByRole('button', { name: 'Begin session' }).click()
}

